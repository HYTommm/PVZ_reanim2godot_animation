void Tscn_PrintAddNode(const Tscn* self, const R2GAStartParam* start_param)
{
    fprintf_s(self->p_file, "; Generated by PVZ_reanim2godot_animation v%s\n\n", VERSION);

    // 添加 AnimationLibrary 资源，一个动画资源对应一个动画库
    // 添加总动画节点
    fprintf_s(self->p_file, "[sub_resource type=\"AnimationLibrary\" id=\"AnimationLibrary_fuck\"]\n"
        "_data = {\n"
        "\"ALL_ANIMS\": SubResource(\"Animation_fuck\")\n"
        "}\n\n");
// 添加每个分动画的 Library 资源，动画资源由 PrintExtResourceToFile 函数导入
    if (start_param->outputMode != OutputMode_TscnByAnim)
        for (int i = 1; i <= self->anims_num; i++)
        {
            fprintf_s(self->p_file, "[sub_resource type=\"AnimationLibrary\" id=\"AnimationLibrary_%s\"]\n", self->anims[i]->res_file_name);
            fprintf_s(self->p_file, "_data = {\n");
            fprintf_s(self->p_file, "&\"%s\": ExtResource(\"%d_anim\")\n", self->anims[i]->res_file_name, i);
            fprintf_s(self->p_file, "}\n");
        }
        // 添加部件节点
        // 添加根节点 Node2D
    fprintf_s(self->p_file, "[node name=\"Node2D\" type=\"Node2D\"]\n\n");
    // 添加每个分动画的 Sprite2D 节点，节点名与分动画名（轨道名）相同
    for (int i = 0; i < self->p_anim->current_tracks_num; i++)
    {
        fprintf_s(self->p_file, "[node name=\"%s\" type=\"Sprite2D\" parent=\".\"]\n", self->p_anim->track_name[i]);
        fprintf_s(self->p_file, "centered = false\n\n");
    }
    // 添加 AnimationPlayer 节点，用于播放动画
    // 添加总动画播放器节点
    fprintf_s(self->p_file,
        "[node name=\"AnimLib\" type=\"AnimationPlayer\" parent=\".\"]\n"
        "libraries = {\n"
        "\"\": SubResource(\"AnimationLibrary_fuck\")\n"
        "}\n\n");
// 添加每个分动画的 AnimationPlayer 节点
    if (start_param->outputMode != OutputMode_TscnByAnim)
        for (int i = 1; i <= self->anims_num; i++)
        {
            fprintf_s(self->p_file,
                "[node name=\"Anim_%s\" type=\"AnimationPlayer\" parent=\".\"]\n"
                "libraries = {\n"
                "\"\": SubResource(\"AnimationLibrary_%s\")\n"
                "}\n\n",
                self->anims[i]->res_file_name, self->anims[i]->res_file_name);
        }
    fflush(self->p_file);
}