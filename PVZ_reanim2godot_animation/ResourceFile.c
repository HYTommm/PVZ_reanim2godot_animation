void Tscn_PrintExtResource(const Tscn* self, const R2GAStartParam* start_param)
{
    if (self == NULL) return;

    // 写入资源引用部分
    fprintf_s(self->p_file, "; Generated by PVZ_reanim2godot_animation v%s\n\n", VERSION);
    fprintf_s(self->p_file, "[gd_scene]\n\n");
    if (start_param->blendModeTrackEnabled)
    {
        fprintf_s(self->p_file,
            "[ext_resource type=\"Shader\" path=\"res://normal.gdshader\" id=\"normal_shader\"]\n"
            "[ext_resource type=\"Shader\" path=\"res://add.gdshader\" id=\"add_shader\"]\n");
    }
    for (int i = 0; i < self->p_anim->texture_filename_times; i++)
    {
        fprintf_s(self->p_file, "[ext_resource type=\"Texture2D\" path=\"%s%s\" id=\"%d_fuck\"]\n", start_param->resourceGodotPath, self->p_anim->texture_filename[i], i);
    }
    fprintf_s(self->p_file, "\n");
    const bool is_ext_anim_enabled = start_param->outputMode != OutputMode_TscnByAnim;
    if (is_ext_anim_enabled)
    {
        if (self->p_anim->anim_index != 0) printf("animation index: %d\n", self->p_anim->anim_index);
        for (int i = 1; i <= self->anims_num; i++)
        {
            if (i == self->p_anim->anim_index)    continue;
            fprintf_s(self->p_file, "[ext_resource type=\"Animation\" path=\"%s%s.tres\" id=\"%d_anim\"]\n", start_param->animOutputGodotPath, self->anims[i]->res_file_name, i);
        }
        fprintf_s(self->p_file, "\n");
    }

    if (start_param->blendModeTrackEnabled)
    {
        fprintf_s(self->p_file,
            "[sub_resource type=\"ShaderMaterial\" id=\"ShaderMaterial_normal\"]\n"
            "shader = ExtResource(\"normal_shader\")\n"
            "\n"
            "[sub_resource type=\"ShaderMaterial\" id=\"ShaderMaterial_add\"]\n"
            "shader = ExtResource(\"add_shader\")\n"
            "\n");
    }
    fflush(self->p_file);
}

