void Tres_Create(Tres* self, PvzAnimation* p_anim)
{
    static _ResourceFile_VTable tres_vtable = {
        .Destroy = Tres_Destroy,
        .Delete = Tres_Delete,
        .OpenOutputFile = Tres_OpenOutputFile,
        .PrintExtResource = Tres_PrintExtResource,
        .PrintSetAnim = Tres_PrintSetAnim,
        .PrintTracks = ResourceFile_PrintTracks
    };
    _ResourceFile_Create((ResourceFile*)self, p_anim);
    self->vptr = (void*)&tres_vtable;
}

void Tres_Destroy(Tres* self)
{
    if (self == NULL) return;
    _ResourceFile_Destroy((ResourceFile*)self);
}

Tres* Tres_New(PvzAnimation* p_anim)
{
    Tres* self = (Tres*)malloc(sizeof(Tres));
    if (!self)    return NULL;
    Tres_Create(self, p_anim);
    return self;
}

void Tres_Delete(Tres* self)
{
    if (!self) return;
    Tres_Destroy(self);
    free(self);
}

void Tres_OpenOutputFile(Tres* self, const char* output_file_path)
{
    sprintf_s(self->name, NAME_LENGTH, "%s%s.tres", output_file_path, *self->name ? self->name : self->p_anim->res_file_name);
    printf("debug: OutputFiles:name--%s\n", self->name);
    FileOpen(&self->p_file, self->name, "w", ErrorCode_CannotOpenOutputFile);
}

void Tres_PrintExtResource(const Tres* self, const R2GAStartParam* const start_param)
{
    if (self == NULL) return;

    // 写入资源引用部分
    fprintf_s(self->p_file, "; Generated by PVZ_reanim2godot_animation v%s\n\n", VERSION);
    fprintf_s(self->p_file, "[gd_resource type=\"Animation\"]\n");
    if (start_param->blendModeTrackEnabled)
    {
        fprintf_s(self->p_file, "[ext_resource type=\"Shader\" path=\"res://normal.gdshader\" id=\"normal_shader\"]\n");
        fprintf_s(self->p_file, "[ext_resource type=\"Shader\" path=\"res://add.gdshader\" id=\"add_shader\"]\n");
    }
    for (int i = 0; i < self->p_anim->texture_filename_times; i++)
    {
        fprintf_s(self->p_file, "[ext_resource type=\"Texture2D\" path=\"%s%s\" id=\"%d_fuck\"]\n", start_param->resourceGodotPath, self->p_anim->texture_filename[i], i);
    }
    fprintf_s(self->p_file, "\n");

    if (start_param->blendModeTrackEnabled)
    {
        fprintf_s(self->p_file,
            "[sub_resource type=\"ShaderMaterial\" id=\"ShaderMaterial_normal\"]\n"
            "shader = ExtResource(\"normal_shader\")\n"
            "\n"
            "[sub_resource type=\"ShaderMaterial\" id=\"ShaderMaterial_add\"]\n"
            "shader = ExtResource(\"add_shader\")\n"
            "\n");
    }
    fflush(self->p_file);
}

void Tres_PrintSetAnim(const Tres* self, const int fps)
{
    fprintf_s(self->p_file, "; Generated by PVZ_reanim2godot_animation v%s\n\n", VERSION);
    fprintf_s(self->p_file, "[resource]\nresource_name = \"%s\"\n", self->p_anim->res_file_name);
    //fprintf_s(self->p_file, "[sub_resource type=\"Animation\" id=\"Animation_fuck\"]\n");
    fprintf_s(self->p_file, "length = %.6Lf\n", (float)(self->p_anim->current_frame_time_num - 1) * (1.0 / fps));
    fprintf_s(self->p_file, "step = %.6Lf\n", 1.0 / fps);
    fflush(self->p_file);
}

