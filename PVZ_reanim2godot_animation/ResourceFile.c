#include "ResourceFile.h"

#include <stdlib.h>
#include <string.h>

#include "FileIO.h"

void _ResourceFile_Create(ResourceFile* self, PvzAnimation* p_anim)
{
    self->p_anim = p_anim;
    self->p_file = NULL;
    memset(self->name, 0, sizeof(self->name));
}

void _ResourceFile_Destroy(ResourceFile* self)
{
    if (self == NULL) return;
    if (self->p_file) FileClose(self->p_file);
    //if (self->p_anim) self->p_anim->vptr->Destroy(self->p_anim);
    self->vptr = NULL;
    self->p_file = NULL;
    self->p_anim = NULL;
}

void ResourceFile_PrintTracks(const ResourceFile* self, const R2GAStartParam* start_param)
{
    self->p_anim->vptr->PrintTracksToFile(self->p_anim, self->p_file, start_param);
}

